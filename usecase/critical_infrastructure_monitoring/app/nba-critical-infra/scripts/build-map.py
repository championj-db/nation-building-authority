"""Build the network map's Australian state outlines from Natural Earth.

Natural Earth (https://www.naturalearthdata.com) is public domain. Download the 1:50m admin-1
GeoJSON, then run:

    python3 -I scripts/build-map.py <path/to/ne_50m_admin_1_states_provinces.geojson>

Writes client/src/lib/australia.ts: simplified, projected SVG paths per state plus the projection
constants, so the client places assets with exactly the same projection as the outlines.
"""

import json
import math
import sys
from pathlib import Path

# Equirectangular projection centred on mainland Australia, x scaled by cos(25 deg S).
LON0, LAT0 = 112.5, -9.5
LON1, LAT1 = 154.2, -44.0
WIDTH = 1000.0
COS = math.cos(math.radians(25))
K = WIDTH / ((LON1 - LON0) * COS)
HEIGHT = round((LAT0 - LAT1) * K, 1)
TOLERANCE = 0.9      # simplification tolerance in SVG units
MIN_AREA = 12.0      # drop islands smaller than this (SVG units^2)

STATE_CODES = {
    "New South Wales": "NSW", "Victoria": "VIC", "Queensland": "QLD", "South Australia": "SA",
    "Western Australia": "WA", "Tasmania": "TAS", "Northern Territory": "NT",
    "Australian Capital Territory": "ACT", "Jervis Bay Territory": "NSW",
}


def project(lon, lat):
    return ((lon - LON0) * K * COS, (LAT0 - lat) * K)


def simplify(points, tol):
    """Douglas-Peucker on a list of (x, y)."""
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    idx, dmax = 0, 0.0
    for i in range(1, len(points) - 1):
        x0, y0 = points[i]
        d = abs(dy * x0 - dx * y0 + x2 * y1 - y2 * x1) / norm
        if d > dmax:
            idx, dmax = i, d
    if dmax <= tol:
        return [points[0], points[-1]]
    return simplify(points[: idx + 1], tol)[:-1] + simplify(points[idx:], tol)


def area(points):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(points, points[1:] + points[:1]))) / 2


def simplify_ring(points, tol):
    """Closed rings start and end on the same point, which degenerates Douglas-Peucker; split the
    ring at the point farthest from its start and simplify the two halves."""
    x0, y0 = points[0]
    far = max(range(len(points)), key=lambda i: math.hypot(points[i][0] - x0, points[i][1] - y0))
    return simplify(points[: far + 1], tol)[:-1] + simplify(points[far:], tol)


def ring_path(ring):
    pts = simplify_ring([project(lon, lat) for lon, lat in ring], TOLERANCE)
    if len(pts) < 4 or area(pts) < MIN_AREA:
        return ""
    return "M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z"


def main(src):
    data = json.loads(Path(src).read_text())
    paths = {}
    for feature in data["features"]:
        props = feature["properties"]
        if props.get("adm0_a3") != "AUS" or props.get("name") not in STATE_CODES:
            continue
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        d = "".join(ring_path(poly[0]) for poly in polys)  # outer rings only
        code = STATE_CODES[props["name"]]
        paths[code] = paths.get(code, "") + d

    order = ["WA", "NT", "SA", "QLD", "NSW", "VIC", "TAS", "ACT"]
    out = Path(__file__).resolve().parent.parent / "client" / "src" / "lib" / "australia.ts"
    lines = [
        "// Generated by scripts/build-map.py from Natural Earth 1:50m admin-1 (public domain).",
        "// Do not edit by hand. Equirectangular projection; see project() below.",
        f"export const MAP_WIDTH = {WIDTH:.0f};",
        f"export const MAP_HEIGHT = {HEIGHT};",
        "",
        f"const LON0 = {LON0};",
        f"const LAT0 = {LAT0};",
        f"const K = {K:.6f};",
        f"const COS = {COS:.6f};",
        "",
        "/** Project longitude/latitude into map coordinates (same projection as the outlines). */",
        "export function project(lon: number, lat: number): [number, number] {",
        "  return [(lon - LON0) * K * COS, (LAT0 - lat) * K];",
        "}",
        "",
        "/** km to map units (approximate, at Australian latitudes). */",
        "export const KM = K / 111.32;",
        "",
        "export const STATES: { code: string; d: string }[] = [",
    ]
    for code in order:
        lines.append(f"  {{ code: '{code}', d: '{paths[code]}' }},")
    lines.append("];")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({out.stat().st_size / 1024:.1f} KB), {MAP_SUMMARY(paths)}")


def MAP_SUMMARY(paths):
    return ", ".join(f"{k}:{v.count('M')} rings" for k, v in paths.items())


if __name__ == "__main__":
    main(sys.argv[1])
