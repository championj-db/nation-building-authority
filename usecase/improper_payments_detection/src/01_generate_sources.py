# Databricks notebook source
# Step 1: bronze sources. Seeded, wholly synthetic, four disconnected systems.
#
# synthetic_world.generate() builds every source table from one seed and a run date, so the same
# seed always gives the same data. Ground truth is written alongside the sources and is used only
# for training labels (05) and for evaluation (07). The model never sees it at scoring time.

# COMMAND ----------

import os
import sys

dbutils.widgets.text("src_dir", "")
_src = dbutils.widgets.get("src_dir").strip()
_src_dir = next((c for c in [_src, os.path.join(_src, "src"), "."] if c and os.path.isfile(os.path.join(c, "common.py"))), None)
if _src_dir is None:
    raise FileNotFoundError("common.py not found - pass src_dir pointing at the use case's src folder")
sys.path.insert(0, _src_dir)

import synthetic_world as sw  # noqa: E402
from common import as_of_date, fq, get_params, record_provenance, write_table  # noqa: E402

params = get_params({"catalog": "", "schema": "", "seed": "42", "as_of": ""}, dbutils)
CATALOG, SCHEMA = params["catalog"], params["schema"]
SEED = int(params["seed"])
AS_OF = as_of_date(params["as_of"])
if not CATALOG or not SCHEMA:
    raise ValueError("catalog and schema parameters are required")
t = lambda name: fq(CATALOG, SCHEMA, name)  # noqa: E731

# COMMAND ----------

tables = sw.generate(SEED, AS_OF)

COMMENTS = {
    "bronze_supplier_master": "SYNTHETIC. Supplier master extract from the accounts payable vendor file. Contains duplicate records and ABN format drift.",
    "bronze_business_registry": "SYNTHETIC. Business registry extract. ABN and legal-name drift; includes cancelled and registry-only entries.",
    "bronze_claimant": "SYNTHETIC. Claimant records. Contains duplicate records with name drift.",
    "bronze_claim": "SYNTHETIC. Claims lodged by claimants, each with an assessing officer.",
    "bronze_officer": "SYNTHETIC. Approving and assessing officers with home addresses.",
    "bronze_payment": "SYNTHETIC. Payment ledger across the supplier and claims programmes.",
    "bronze_ground_truth": "SYNTHETIC. Injected improper-payment patterns and benign look-alikes. Used only for training labels and evaluation.",
}
for name, pdf in tables.items():
    print(f"{name}: {write_table(spark, pdf, t(name), COMMENTS[name])} rows")

record_provenance(spark, t("pipeline_provenance"), "01_generate_sources", [
    ("improper_payments_synthetic_world", "None - synthetic", "", "Generated by src/synthetic_world.py",
     "Synthetic, seeded; no real person or business", len(tables["bronze_payment"]), False, None),
])
